#!/usr/bin/env python3
"""
Correlated ("nearby") wrong partial-key classes in the last counting stage of
the 17-round SAND-64 and 23-round SAND-128 attacks (Section 7.3.1 of the paper).

The wrong-key randomization hypothesis gives every wrong class a background
counter Poisson(N 2^-b).  A class that differs from the correct one in a few
bits, however, evaluates the last difference test identically on a fixed
fraction rho of the pairs counted by the correct class, so its counter is about
Poisson(N p rho + N 2^-b).  This script measures rho and evaluates

    E[N_wrong] = sum_{kappa != kappa*} Pr[c_kappa >= tau],

which needs no independence between the counters.

Method.  Right pairs are generated by fixing the difference at the
plaintext-side end of the differential and decrypting the prepended rounds
under a random key.  The partial key is split into a "head" (sk^0 for SAND-128;
sk^0 and sk^1 for SAND-64) and the round key used by the last test (sk^1 resp.
sk^2).  A flip of the last key acts column by column on disjoint output bits, so
its 8^|J| values are combined exactly by a pruned depth-first search; the head
is enumerated exhaustively up to Hamming distance 2 from the correct one and
sampled at larger distances.  Classes with rho < 0.05 are treated as background.

Usage:  python3 nearby_classes.py {64|128} [seed] [samples] [dmax] [--json FILE]
        e.g. python3 nearby_classes.py 128 23 1500 9     (about 45 min)
             python3 nearby_classes.py 64  23 1500 6     (a few minutes)

Requires numpy.  The rest of the repository uses the standard library only.
"""
import itertools
import json
import math
import sys

import numpy as np

from sand_np import SAND, rnd

args = [a for a in sys.argv[1:] if not a.startswith("--")]
VAR = args[0]
SEED = int(args[1]) if len(args) > 1 else 23
NS = int(args[2]) if len(args) > 2 else 1500
DMAX = int(args[3]) if len(args) > 3 else (9 if VAR == "128" else 6)
JSON_OUT = sys.argv[sys.argv.index("--json") + 1] if "--json" in sys.argv else None

rng = np.random.default_rng(SEED)
NP = 2048                 # right pairs used to measure rho
LAM_R = 32.0              # E[c_*] = N p = 2^5 in both attacks
TAUS = [10, 12, 13, 14, 15, 16]
U = np.uint64


def poisson_sf(lam, k):
    """Pr[Poisson(lam) >= k]."""
    if lam < k:             # sum the tail directly; 1 - cdf would underflow
        t = math.exp(-lam + k * math.log(lam) - math.lgamma(k + 1))
        s, i = 0.0, k
        while t > 1e-30 * max(s, 1e-300):
            s += t
            i += 1
            t *= lam / i
        return s
    s, t = 0.0, math.exp(-lam)
    for i in range(k):
        s += t
        t *= lam / (i + 1)
    return max(0.0, 1.0 - s)


def back(S, x, y, keys):
    for k in reversed(keys):
        x, y = y, x ^ S.f(y) ^ k
    return x, y


if VAR == "128":
    S = SAND(64); n, w = 64, 16
    DXS, DYS = 0x1115, 0xCC0C          # (dX^3, dY^3), plaintext-side end
    DX2, TARGET = 0xCC0C, 0x1115
    MK0, MK1 = 0xFE3FFF3FFF3BFF3F, 0xCC0CCC0CCC0C0000
    J, LROWS = [15, 14, 11, 10, 3, 2], [3, 2, 1]
    LAM_B, TAU_PAPER = 2.0 ** -3, 14
    sk = [rnd(rng, n, 1)[0] for _ in range(3)]
    x0 = rnd(rng, n, NP); y0 = rnd(rng, n, NP)
    A = back(S, x0, y0, sk)
    B = back(S, x0 ^ U(DXS), y0 ^ U(DYS), sk)
    head_masks = [MK0]
    true_head = [sk[0]]
    last_key, last_mask = sk[1], MK1

    def head(hk):
        """Stage-1 pass vector, x^2 xor sk^1 for both members, and dX^1."""
        (xa, ya), (xb, yb) = A, B
        x1a, x1b = ya ^ S.f(xa) ^ hk[0], yb ^ S.f(xb) ^ hk[0]
        fa, fb = S.f(x1a), S.f(x1b)
        st = ((xa ^ xb) ^ fa ^ fb) == U(DX2)
        return st, xa ^ fa, xb ^ fb, x1a ^ x1b

    def var_bits(j):        # variable output bits of SSb j after P_n
        p = S.p
        return [w * 3 + p[j], w * 1 + p[(j + 1) % w]]
else:
    S = SAND(32); n, w = 32, 8
    DXS, DYS = 0x00900000, 0x008C0000  # (dX^4, dY^4)
    DX3, TARGET = 0x008C0000, 0x00900000
    MX2, VX2 = 0xB9FF37B9, 0x001E0000
    MK0, MK1, MK2 = 0xFFFFFFFF, 0xDFDFDFDF, 0x8C008C8C
    J, LROWS = [7, 3, 2], [3, 1, 0]
    LAM_B, TAU_PAPER = 2.0 ** -2, 16
    sk = [rnd(rng, n, 1)[0] for _ in range(4)]
    x0 = rnd(rng, n, NP); y0 = rnd(rng, n, NP)
    A = back(S, x0, y0, sk)
    B = back(S, x0 ^ U(DXS), y0 ^ U(DYS), sk)
    head_masks = [MK0, MK1]
    true_head = [sk[0], sk[1]]
    last_key, last_mask = sk[2], MK2

    def head(hk):
        (xa, ya), (xb, yb) = A, B
        x1a, x1b = ya ^ S.f(xa) ^ hk[0], yb ^ S.f(xb) ^ hk[0]
        fa, fb = S.f(x1a), S.f(x1b)
        x2a, x2b = xa ^ fa ^ hk[1], xb ^ fb ^ hk[1]
        dx2 = x2a ^ x2b
        st = (dx2 & U(MX2)) == U(VX2)
        ga, gb = S.f(x2a), S.f(x2b)
        st &= ((x1a ^ x1b) ^ ga ^ gb) == U(DX3)
        return st, x1a ^ ga, x1b ^ gb, dx2

    def var_bits(j):
        p = S.p
        return [w * 3 + p[j], w * 0 + p[j], w * 1 + p[(j + 1) % w]]

FULL = (1 << n) - 1


def last_test(st, z, zs, d, k):
    return st & ((d ^ S.f(z ^ k) ^ S.f(zs ^ k)) == U(TARGET))


def column_vectors(hk):
    """Pass vectors of the column-j conditions for each of the 8 last-key flips."""
    st, z, zs, d = head(hk)
    cols = []
    for j in J:
        vecs = []
        for e in range(8):
            flip = sum(((e >> t) & 1) << (w * r + j) for t, r in enumerate(LROWS))
            k = last_key ^ U(flip)
            err = d ^ S.f(z ^ k) ^ S.f(zs ^ k) ^ U(TARGET)
            ok = st.copy()
            for b in var_bits(j):
                ok &= ((err >> U(b)) & U(1)) == U(0)
            vecs.append(ok)
        cols.append(vecs)
    return st, cols


CMIN = int(0.05 * NP)


def classes(cols, skip_correct):
    """Counts of all last-key flips with rho >= 0.05 (pruned DFS)."""
    out = []

    def rec(i, acc, nz):
        c = int(acc.sum())
        if c < CMIN:
            return
        if i == len(cols):
            if not (skip_correct and not nz):
                out.append(c)
            return
        for e in range(8):
            rec(i + 1, acc & cols[i][e], nz or e != 0)
    rec(0, np.ones(NP, bool), False)
    return out


def contrib(counts):
    return np.array([sum(poisson_sf(LAM_R * c / NP + LAM_B, t) for c in counts)
                     for t in TAUS])


def fmt(v):
    return {t: round(float(x), 3) for t, x in zip(TAUS, v)}


# ---- sanity: correct class counts every pair, masks are sufficient ---------
rk = [(h & U(M)) | (rnd(rng, n, 1)[0] & U(~M & FULL)) for h, M in zip(true_head, head_masks)]
st, z, zs, d = head(rk)
kl = (last_key & U(last_mask)) | (rnd(rng, n, 1)[0] & U(~last_mask & FULL))
suff = int(last_test(st, z, zs, d, kl).sum())
print(f"SAND-{VAR}, seed {SEED}: mask sufficiency {suff}/{NP}")
assert suff == NP

# ---- head correct: wrong last-key flips only --------------------------------
st, cols = column_vectors(true_head)
cnt = classes(cols, skip_correct=True)
hist = {}
for c in cnt:
    r = round(c / NP, 2)
    hist[r] = hist.get(r, 0) + 1
E0 = contrib(cnt)
TOT = E0.copy()
print(f"head correct: {len(cnt)} classes with rho >= 0.05")
print("  rho histogram:", sorted(hist.items(), reverse=True)[:12])
print("  E contribution:", fmt(E0))
per_d = {0: fmt(E0)}

# ---- head at Hamming distance d ---------------------------------------------
hbits = [(i, b) for i, M in enumerate(head_masks) for b in range(n) if (M >> b) & 1]
for dd in range(1, DMAX + 1):
    tot = math.comb(len(hbits), dd)
    if tot <= NS:
        samples, scale = list(itertools.combinations(hbits, dd)), 1.0
    else:
        samples = [tuple(hbits[i] for i in rng.choice(len(hbits), dd, replace=False))
                   for _ in range(NS)]
        scale = tot / NS
    Ed, nsig = np.zeros(len(TAUS)), 0
    for fl in samples:
        hk = list(true_head)
        for i, b in fl:
            hk[i] = hk[i] ^ U(1 << b)
        st, cols = column_vectors(hk)
        if st.sum() < CMIN:
            continue
        c = classes(cols, skip_correct=False)
        nsig += len(c)
        Ed += contrib(c)
    TOT += Ed * scale
    per_d[dd] = fmt(Ed * scale)
    print(f"d={dd} variants={tot} sampled={len(samples)} sig={nsig} E_d:", fmt(Ed * scale),
          flush=True)
    print("   cumulative:", fmt(TOT), flush=True)

M = 2 ** (69 if VAR == "64" else 72) - 1
bg = {t: M * poisson_sf(LAM_B, t) for t in TAUS}
print("\nbackground (2^k - 1) Pr[Poisson(N 2^-b) >= tau]:",
      {t: f"{v:.4g}" for t, v in bg.items()})
print("nearby E[N_wrong]:", fmt(TOT))
print(f"at the paper's tau = {TAU_PAPER}: nearby {TOT[TAUS.index(TAU_PAPER)]:.1f}, "
      f"background {bg[TAU_PAPER]:.4g}")

if JSON_OUT:
    json.dump(dict(variant=VAR, seed=SEED, samples=NS, dmax=DMAX, pairs=NP,
                   taus=TAUS, per_distance=per_d, nearby=fmt(TOT),
                   background={t: bg[t] for t in TAUS}), open(JSON_OUT, "w"), indent=1)
